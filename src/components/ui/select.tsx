interface FormSelectProps {
  label?: string
  error?: string
  description?: string
  value?: string
  onValueChange?: (value: string) => void
  required?: boolean
  id?: string
  children: React.ReactNode
}

function FormSelect({
  label,
  error,
  description,
  value,
  onValueChange,
  required,
  id: idProp,
  children,
  ...rootProps
}: FormSelectProps & Omit<React.ComponentProps<typeof SelectPrimitive.Root>, "value" | "onValueChange">) {
  const generatedId = React.useId()
  const id = idProp ?? (label ? label.replace(/\s+/g, "-").toLowerCase() : undefined) ?? generatedId
  const childArray = React.Children.toArray(children)
  const withTriggerId = childArray.map((child, index) => {
    if (
      index === 0 &&
      React.isValidElement(child) &&
      (child as React.ReactElement<{ id?: string }>).props?.id === undefined
    ) {
      return React.cloneElement(child as React.ReactElement<{ id?: string }>, { id })
    }
    return child
  })
  return (
    <div className="w-full">
      {label && (
        <Label htmlFor={id} className="block text-sm font-medium text-foreground/90 mb-1">
          {label}
          {required && <span className="text-destructive ml-0.5">*</span>}
        </Label>
      )}
      {description && <p className="text-xs text-muted-foreground mb-1.5">{description}</p>}
      <Select
        value={value}
        onValueChange={onValueChange}
        required={required}
        aria-invalid={!!error}
        {...rootProps}
      >
        {withTriggerId}
      </Select>
      {error && (
        <p className="mt-1 text-xs text-destructive flex items-center gap-1">
          <AlertCircle className="h-3 w-3 shrink-0" />
          {error}
        </p>
      )}
    </div>
  )
}

